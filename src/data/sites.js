export function getCountryFlagCode(country) {
  if (!country) return 'eu';
  const mainCountry = country.split(/[/,、・\s]+/)[0].trim();
  return COUNTRY_TO_ISO[mainCountry] || COUNTRY_TO_ISO[country] || 'eu';
}

export function getCountryFlagHtml(country, extraClass = '') {
  const code = getCountryFlagCode(country);
  const src = `./images/flags/${code}.svg`;
  return `<img src="${src}" alt="${country}" class="flag-icon ${extraClass}" loading="lazy" onError="this.onerror=null;this.src='./images/flags/eu.svg';" />`;
}

